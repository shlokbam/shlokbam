def notes_items(c, journal):
    fn = c['field_notes']
    posts = sorted(fn['posts'], key=lambda p: p['date'], reverse=True)
    if fn.get('series'):
        items = [p for p in posts if p.get('series') == fn['series']][:3]
        right = f'now writing · {fn["series"]}' + (f' · {fn["series_note"]}' if fn.get('series_note') else '')
    else:
        pool = posts + [{'date': j['date'] or '', 'title': j['title'], 'source': 'journal', 'url': j['url'], 'code': ''} for j in journal]
        items = sorted(pool, key=lambda p: p['date'], reverse=True)[:3]
        right = 'latest writing'
    return items, right


