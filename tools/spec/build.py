def tw(text, size, font='body'):
    """Text width in px, from the real font metrics (mono: fixed 0.6 em)."""
    if font == 'mono':
        return len(text) * 0.6 * size
    cmap, hmtx, upm = _met[font]
    return sum(hmtx[cmap.get(ord(c), cmap[ord('n')])][0] for c in text) * size / upm


def wrap(text, size, width, font='body'):
    lines, cur = [], ''
    for word in text.split():
        trial = (cur + ' ' + word).strip()
        if tw(trial, size, font) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    return lines + ([cur] if cur else [])


def esc(s):
    return html.escape(str(s), quote=True)


