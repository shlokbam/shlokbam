def dailydiff_status(sysd):
    """Last run of the DailyDiff workflow, via the public Actions API."""
    if OFFLINE:
        return sysd.get('_last', ('running', MUTED))
    try:
        runs = json.loads(legacy.get(f'https://api.github.com/repos/{sysd["repo"]}/actions/runs?per_page=1&branch=main'))
        r = runs['workflow_runs'][0]
        day = r['updated_at'][:10]
        d = datetime.date.fromisoformat(day).strftime('%d %b').lstrip('0')
        if r['conclusion'] == 'success':
            return f'last run ok · {d}', GREEN
        if r['status'] != 'completed':
            return 'running now', ORANGE
        return f'last run {r["conclusion"]} · {d}', ORANGE
    except Exception as e:
        print('WARNING: DailyDiff status not read:', e)
        return 'running', GREEN


